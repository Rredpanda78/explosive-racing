/** 加速帶：dist 為距起跑線的公尺數，lat 為橫向位置（左為正） */
export interface BoostPad {
  dist: number;
  lat: number;
}

export type ThemeId = 'meadow' | 'desert' | 'city' | 'ocean' | 'taiwan';

/** 沿賽道的一段範圍（公尺）；side：1 = 行進方向左側，-1 = 右側，0 = 兩側 */
export interface SceneRange {
  from: number;
  to: number;
  side: number;
}

/** 賽道旁要擺哪些大型景物 */
export interface Scenery {
  stands: SceneRange[];
  pits: SceneRange[];
  tents: SceneRange[];
  /** 橫跨路面的拱門位置 */
  arches: number[];
}

export interface TrackDef {
  id: string;
  name: string;
  /** 選單上的一句話介紹 */
  desc: string;
  theme: ThemeId;
  scenery: Scenery;
  laps: number;
  halfWidth: number;
  /** 控制點 [x, z, 高度] */
  points: [number, number, number][];
  pads: BoostPad[];
  /** 跳台（距起跑線的公尺數，指跳台頂端的位置），整條路寬都是斜坡 */
  ramps: number[];
  /** 爆炸桶的位置 */
  barrels: BoostPad[];
  /** 捷徑：從主線分岔、抄近路再接回主線的窄路 */
  shortcuts?: ShortcutDef[];
  /** 賽道機關 */
  hazards?: HazardDef[];
  /**
   * 軟邊界：路緣外可以開的砂石緩衝區寬度（公尺）。沒設定 = 路邊直接是護欄（原本的行為）。
   * 實際寬度會依每個取樣點自動縮小：不能跟別段賽道或捷徑的緩衝區疊在一起、彎道內側不能寬到可以抄捷徑，
   * 太窄就乾脆維持護欄。緩衝區外面是岩石／輪胎牆（撞到跟撞牆一樣），或是台地邊緣的懸崖。
   */
  runoff?: number;
  /** 個別路段的緩衝區設定（後面的蓋過前面的） */
  runoffZones?: RunoffZone[];
  /** 緩衝區的地面：沒設定就依主題（沙漠 = 砂石、草原 = 草地、城市 = 鋪面） */
  runoffSurface?: RunoffSurface;
}

export type RunoffSurface = 'sand' | 'grass' | 'paved' | 'forest';

/** 一段路的緩衝區設定：from / to 為距起跑線的公尺數，side：1 = 左側、-1 = 右側、0 = 兩側 */
export interface RunoffZone {
  from: number;
  to: number;
  side: number;
  /** 這段想要的寬度（0 = 維持護欄）；沒設定就用賽道的 runoff */
  width?: number;
  /** 緩衝區外側是懸崖：開出去就摔下去（跟沒有護欄的捷徑一樣），不是撞到岩石 */
  cliff?: boolean;
}

/** 緩衝區與別段賽道（或捷徑）之間至少要留的距離：兩邊的外圍屏障不會疊在一起，車在緩衝區裡也不會被判到別段路上 */
const RUNOFF_MARGIN = 4;
/** 算出來比這個窄的地方就維持護欄（例如平行的兩條直線之間） */
const RUNOFF_MIN = 7;
/** 寬度沿賽道每前進 1 公尺最多變化多少：緩衝區收窄的地方，外圍屏障斜斜地收進來，不會突然出現一道橫牆 */
const RUNOFF_TAPER = 0.5;
/** 彎道內側最多只能用「內緣半徑 × 這個比例」當緩衝區：不能從髮夾彎內側的沙地抄近路 */
const RUNOFF_INNER = 0.45;
/** 捷徑兩側的岩壁要留的厚度 */
const RUNOFF_BRANCH_GAP = 3;
/** 車身中心超出路緣多少公尺才算開進緩衝區（壓在路緣石上沒有懲罰） */
export const KERB_WIDTH = 1.0;

/**
 * 捷徑：from / to 是在主線上分岔與接回的位置（公尺），lat 是兩端在主線上的橫向位置（正 = 左，
 * 一般靠彎道內側）。中間可以指定經過的點 [x, z]。兩端與主線相切，所以會先和主線重疊一段再分開。
 */
export interface ShortcutDef {
  from: number;
  to: number;
  lat: number;
  via?: [number, number][];
  halfWidth: number;
  /** 入口指示牌上的名字 */
  name?: string;
  /** 碎石、泥地：沒有加速效果（N2O、小噴、加速帶）時極速只剩這個倍率——要帶著 N2O 進去才划算 */
  rough?: number;
  /** fall = 沒有護欄，開出路面就摔下去（回到主線、停下來，損失好幾秒） */
  edge?: 'wall' | 'fall';
  /** 路上的障礙物（石頭、樹、施工桶）：u = 沿捷徑的位置比例 0~1，lat = 橫向位置，r = 半徑 */
  posts?: { u: number; lat: number; r?: number }[];
}

/** 捷徑上的障礙物（世界座標） */
export interface Post { x: number; z: number; y: number; r: number; d: number; lat: number }

/**
 * 機關：
 * - hammer：吊在門架上左右擺盪的大鐵鎚
 * - boulder：從路邊滾進賽道、沿著下坡往前滾的巨石（len 為滾動的路段長度，period 為生成間隔）
 * - tram：橫越路口的電車，period 秒一班（train = 平交道的區間車：更長、更快）
 * - scooter：機車（src/game/street.ts）。沒有 len = 從路口的巷子橫越馬路的一群機車；
 *   有 len = 沿著路邊（lat）騎 len 公尺的機車，period 秒出發一台
 * - firecracker：鞭炮區（src/game/street.ts）：從 dist 開始 len 公尺內，鋪在路面上的幾串鞭炮輪流引爆
 * - gust：河堤強風（src/game/street.ts）：從 dist 開始 len 公尺內，一陣一陣把車往側邊推
 */
export interface HazardDef {
  kind: 'hammer' | 'boulder' | 'tram' | 'scooter' | 'firecracker' | 'gust';
  dist: number;
  period: number;
  phase?: number;
  len?: number;
  /** 沿路騎的機車所在的橫向位置（左為正） */
  lat?: number;
  /** 平交道的火車（畫面與尺寸跟電車不同） */
  train?: boolean;
}

