/** 英文序數：1st、2nd、3rd、4th… */
export function ordinal(n: number): string {
  const v = n % 100;
  return n + (v >= 11 && v <= 13 ? 'th' : (['th', 'st', 'nd', 'rd'][n % 10] ?? 'th'));
}

